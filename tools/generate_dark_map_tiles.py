import math
import io
import urllib.request
from PIL import Image, ImageOps, ImageEnhance

WIDTH = 320
HEIGHT = 240

# Configure your custom city & zoom levels here (Lat, Lon, Zoom, C++ symbol name)
CITIES_AND_ZOOMS = [
    (38.7205, 35.4826, 7,  "kMapKayseriZ7"),
    (38.7205, 35.4826, 8,  "kMapKayseriZ8"),
    (38.7205, 35.4826, 9,  "kMapKayseriZ9"),
    (38.7205, 35.4826, 10, "kMapKayseriZ10"),
    (38.7205, 35.4826, 11, "kMapKayseriZ11"),
    (38.7205, 35.4826, 12, "kMapKayseriZ12"),
    (41.0082, 28.9784, 9,  "kMapIstanbulZ9"),
    (39.9334, 32.8597, 9,  "kMapAnkaraZ9"),
    (36.8969, 30.7133, 9,  "kMapAntalyaZ9"),
    (40.6413, -73.7781, 11, "kMapNewYorkZ11"),
]


def latlon_to_xy(lat: float, lon: float, zoom: int):
    lat_rad = math.radians(lat)
    n = 2.0 ** zoom
    x = (lon + 180.0) / 360.0 * n * 256.0
    y = (1.0 - math.asinh(math.tan(lat_rad)) / math.pi) / 2.0 * n * 256.0
    return x, y


def fetch_stitched_map(lat: float, lon: float, zoom: int) -> Image.Image:
    cx, cy = latlon_to_xy(lat, lon, zoom)
    left = int(cx - WIDTH // 2)
    top = int(cy - HEIGHT // 2)
    tx_min = left // 256
    tx_max = (left + WIDTH - 1) // 256
    ty_min = top // 256
    ty_max = (top + HEIGHT - 1) // 256

    canvas = Image.new("RGB", ((tx_max - tx_min + 1) * 256, (ty_max - ty_min + 1) * 256))
    for ty in range(ty_min, ty_max + 1):
        for tx in range(tx_min, tx_max + 1):
            url = f"https://mt1.google.com/vt/lyrs=m&hl=tr&x={tx}&y={ty}&z={zoom}"
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=15) as resp:
                tile = Image.open(io.BytesIO(resp.read())).convert("RGB")
            canvas.paste(tile, ((tx - tx_min) * 256, (ty - ty_min) * 256))

    crop_x = left - tx_min * 256
    crop_y = top - ty_min * 256
    cropped = canvas.crop((crop_x, crop_y, crop_x + WIDTH, crop_y + HEIGHT))

    # Convert to crisp monochrome dark-mode suitable for RGB565 TFT display
    inv = ImageOps.invert(cropped)
    gray = ImageOps.grayscale(inv)
    gray = ImageEnhance.Contrast(gray).enhance(1.35)
    return gray.convert("RGB")


def rgb_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    print("Generating include/real_map_tiles.h ...")
    lines = [
        "/*",
        " * SPDX-License-Identifier: CC-BY-NC-SA-4.0",
        " * Copyright (c) 2026 Yash Mulgaonkar - https://github.com/yashmulgaonkar/FlightScnr_Pi",
        " * Generated by tools/generate_dark_map_tiles.py",
        " */",
        "#pragma once",
        "#include <Arduino.h>",
        "#include <pgmspace.h>",
        "",
        "struct RealMapTile {",
        "    float centerLat;",
        "    float centerLon;",
        "    uint8_t zoom;",
        "    uint16_t palette[16];",
        "    const uint8_t* pixels;",
        "};",
        "",
    ]

    for lat, lon, zoom, name in CITIES_AND_ZOOMS:
        print(f"Fetching {name} ({lat}, {lon}, z={zoom})...")
        img = fetch_stitched_map(lat, lon, zoom)
        q = img.quantize(colors=16, method=Image.Quantize.MEDIANCUT)
        raw_pal = q.getpalette()[:48]
        pal565 = []
        for i in range(16):
            r, g, b = raw_pal[i * 3 : i * 3 + 3]
            pal565.append(f"0x{rgb_to_rgb565(r, g, b):04X}")

        pix = list(q.getdata())
        packed = []
        for i in range(0, len(pix), 2):
            b = ((pix[i] & 0x0F) << 4) | (pix[i + 1] & 0x0F)
            packed.append(f"0x{b:02X}")

        lines.append(f"const uint8_t {name}_pix[38400] PROGMEM = {{")
        for row in range(0, len(packed), 32):
            lines.append("    " + ",".join(packed[row : row + 32]) + ",")
        lines.append("};")
        lines.append(f"const RealMapTile {name} PROGMEM = {{")
        lines.append(f"    {lat:.4f}f, {lon:.4f}f, {zoom},")
        lines.append("    {" + ", ".join(pal565) + "},")
        lines.append(f"    {name}_pix")
        lines.append("};\n")

    with open("include/real_map_tiles.h", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("Done! Saved to include/real_map_tiles.h")


if __name__ == "__main__":
    main()
